import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const GENERATED = path.join(ROOT, "generated");

interface PublicInputField {
  name: string;
  type: string;
}

const publicInputs = JSON.parse(
  fs.readFileSync(path.join(ROOT, "public-inputs.json"), "utf8"),
) as { version: number; fields: PublicInputField[] };
const protocol = JSON.parse(
  fs.readFileSync(path.join(ROOT, "protocol.json"), "utf8"),
) as Record<string, string | number>;
const contracts = JSON.parse(
  fs.readFileSync(path.join(ROOT, "contracts.json"), "utf8"),
) as {
  env: Record<string, string>;
  compliance: Record<string, string>;
  verifier: Record<string, string>;
};

const fields = publicInputs.fields;

fs.mkdirSync(GENERATED, { recursive: true });

const fieldNames = fields.map((f) => f.name);

const ts = `// AUTO-GENERATED by bindings/scripts/generate.ts — do not edit
export const PUBLIC_INPUT_VERSION = ${publicInputs.version} as const;
export const PUBLIC_INPUT_COUNT = ${fields.length} as const;

export const PUBLIC_INPUT_FIELDS = [
${fieldNames.map((n) => `  "${n}",`).join("\n")}
] as const;

export type PublicInputField = (typeof PUBLIC_INPUT_FIELDS)[number];

export const PUBLIC_INPUT_FIELD_TYPES: Record<PublicInputField, string> = {
${fields.map((f) => `  ${f.name}: "${f.type}",`).join("\n")}
};

export function publicInputIndex(name: PublicInputField): number {
  const idx = PUBLIC_INPUT_FIELDS.indexOf(name);
  if (idx < 0) throw new Error(\`unknown public input field: \${name}\`);
  return idx;
}

export const PROTOCOL = {
  EPOCH_LEN_SECS: ${protocol.EPOCH_LEN_SECS},
  MAX_EPOCH_LAG: ${protocol.MAX_EPOCH_LAG},
  MERKLE_DEPTH: ${protocol.MERKLE_DEPTH},
  NULLIFIER_DOMAIN_TAG: BigInt("${BigInt(protocol.NULLIFIER_DOMAIN_TAG as string)}"),
  CORRIDOR_DOMAIN_TAG: BigInt("${BigInt(protocol.CORRIDOR_DOMAIN_TAG as string)}"),
  CORRIDOR_ID: ${protocol.CORRIDOR_ID},
} as const;
`;

const rs = `// AUTO-GENERATED by bindings/scripts/generate.ts — do not edit
#[allow(dead_code)]
pub const PUBLIC_INPUT_VERSION: u32 = ${publicInputs.version};
pub const PUBLIC_INPUT_COUNT: u32 = ${fields.length};

pub const PUBLIC_INPUT_FIELDS: [&str; ${fields.length}] = [
${fieldNames.map((n) => `    "${n}",`).join("\n")}
];

pub const EPOCH_LEN_SECS: u64 = ${protocol.EPOCH_LEN_SECS};
pub const MAX_EPOCH_LAG: u64 = ${protocol.MAX_EPOCH_LAG};
pub const MERKLE_DEPTH: usize = ${protocol.MERKLE_DEPTH};
`;

const contractsTs = `// AUTO-GENERATED by bindings/scripts/generate.ts — do not edit
export const CONTRACT_ENV = {
${Object.entries(contracts.env)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n")}
} as const;

export const COMPLIANCE_METHODS = {
${Object.entries(contracts.compliance)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n")}
} as const;

export const VERIFIER_METHODS = {
${Object.entries(contracts.verifier)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n")}
} as const;
`;

fs.writeFileSync(path.join(GENERATED, "publicInputs.ts"), ts);
fs.writeFileSync(path.join(GENERATED, "public_inputs.rs"), rs);
fs.writeFileSync(path.join(GENERATED, "contracts.ts"), contractsTs);

console.log("Generated bindings:", GENERATED);
