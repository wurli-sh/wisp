function sbox5(x) {
  const x2 = F.mul(x, x);
  const x4 = F.mul(x2, x2);
  return F.mul(x4, x);
}

function matFull4(inp) {
  const t0 = F.add(inp[0], inp[1]);
  const t1 = F.add(inp[2], inp[3]);
  const t2 = F.add(F.mul(inp[1], mod(2)), t1);
  const t3 = F.add(F.mul(inp[3], mod(2)), t0);
  const t4 = F.add(F.mul(t1, mod(4)), t3);
  const t5 = F.add(F.mul(t0, mod(4)), t2);
  const t6 = F.add(t3, t5);
  const t7 = F.add(t2, t4);
  return [t6, t5, t7, t4];
}

export function poseidon2Permutation(stateIn) {
  const state = Array.from({ length: 65 }, () => [mod(0), mod(0), mod(0), mod(0)]);
  for (let j = 0; j < 4; j++) state[0][j] = mod(stateIn[j]);

  for (let r = 0; r < 64; r++) {
    const arc = RC[r].map((c, j) => F.add(state[r][j], mod(c)));
    if (r < 4 || r >= 60) {
      const f = r < 4 ? r : r - 56;
      const sboxed = arc.map((v) => sbox5(v));
      const out = matFull4(sboxed);
      for (let j = 0; j < 4; j++) state[r + 1][j] = out[j];
    } else {
      const p = r - 4;
      const partial = sbox5(arc[0]);
      const partialSum = F.add(F.add(F.add(partial, arc[1]), arc[2]), arc[3]);
      state[r + 1][0] = F.add(F.mul(partial, mod(INTERNAL_DIAG[0])), partialSum);
      state[r + 1][1] = F.add(F.mul(arc[1], mod(INTERNAL_DIAG[1])), partialSum);
      state[r + 1][2] = F.add(F.mul(arc[2], mod(INTERNAL_DIAG[2])), partialSum);
      state[r + 1][3] = F.add(F.mul(arc[3], mod(INTERNAL_DIAG[3])), partialSum);
    }
  }
  return state[64];
}

export function poseidon2Hash1(input) {
  const iv = mod(TWO_POW_64);
  const out = poseidon2Permutation([mod(input), mod(0), mod(0), iv]);
  return out[0];
}

export function poseidon2Hash2(a, b) {
  const iv = mod(2n * TWO_POW_64);
  const out = poseidon2Permutation([mod(a), mod(b), mod(0), iv]);
  return out[0];
}

