#!/usr/bin/env bash
# Start issuer-service + frontend dev server (testnet profile).
# Usage: ./scripts/dev/bru.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PIDFILE="${ROOT}/.wisp/issuer-service.pid"
LOGFILE="${ROOT}/.wisp/issuer-service.log"
FRONTEND_PORT="${FRONTEND_PORT:-5173}"
cd "$ROOT"

log_bru() { echo "[bru] $*"; }

set -a
# shellcheck disable=SC1091
[[ -f "${ROOT}/.env" ]] && source "${ROOT}/.env"
# shellcheck disable=SC1091
[[ -f "${ROOT}/.wisp/testnet-demo.env" ]] && source "${ROOT}/.wisp/testnet-demo.env"
# shellcheck disable=SC1091
[[ -f "${ROOT}/.wisp/compliance.env" ]] && source "${ROOT}/.wisp/compliance.env"
set +a

if [[ -n "${SUPABASE_DB_POOLER_URL:-}" ]] && [[ "${WISP_ENV:-}" == "production" || -n "${RENDER:-}" ]]; then
  export SUPABASE_DB_URL="${SUPABASE_DB_POOLER_URL}"
  export DATABASE_URL="${SUPABASE_DB_POOLER_URL}"
fi

export ISSUER_LISTEN_ADDR="${ISSUER_LISTEN_ADDR:-127.0.0.1:3000}"
export ISSUER_STATE_PATH="${ROOT}/.wisp/issuer-state-testnet.json"
export ISSUER_API_TOKEN="${ISSUER_API_TOKEN:-demo-token}"
export WISP_FIXTURES_DIR="${WISP_FIXTURES_DIR:-${ROOT}/bindings/fixtures}"
export WISP_FIXTURE_PROFILE="${WISP_FIXTURE_PROFILE:-testnet}"
export COMPLIANCE_CONTRACT_ID="${COMPLIANCE_ID:-${COMPLIANCE_CONTRACT_ID:-}}"
export VERIFIER_CONTRACT_ID="${VERIFIER_ID:-${VERIFIER_CONTRACT_ID:-}}"
export EXPECTED_VK_HASH="${VK_HASH:-${EXPECTED_VK_HASH:-}}"
export ISSUER_PUBLIC_KEY="${ISSUER_PUBLIC_KEY:-}"
export PUBLISH_SOURCE_ACCOUNT="${PUBLISH_SOURCE_ACCOUNT:-amoeba-issuer}"
export ADMIN_PUBLIC_KEY="${ADMIN_PUBLIC_KEY:-$(stellar keys public-key "amoeba-admin" 2>/dev/null || true)}"
export STELLAR_RPC_URL="${STELLAR_RPC_URL:-https://soroban-testnet.stellar.org}"
export NETWORK_PASSPHRASE="${NETWORK_PASSPHRASE:-Test SDF Network ; September 2015}"
export STELLAR_NETWORK_PASSPHRASE="${STELLAR_NETWORK_PASSPHRASE:-$NETWORK_PASSPHRASE}"
export WEB_AUTH_DOMAIN="${WEB_AUTH_DOMAIN:-localhost}"
export HORIZON_URL="${HORIZON_URL:-https://horizon-testnet.stellar.org}"
export KYC_MODE="${KYC_MODE:-sep10}"
export RUST_LOG="${RUST_LOG:-issuer_service=info,tower_http=warn}"
export PROVIDER_WEBHOOK_SECRETS="${PROVIDER_WEBHOOK_SECRETS:-fixture=demo-fixture-secret}"

REQUIRE_DB=0
if [[ "${ISSUER_REQUIRE_DB:-}" == "1" || "${WISP_ENV:-}" == "production" || -n "${RENDER:-}" ]]; then
  REQUIRE_DB=1
fi

if [[ -z "${COMPLIANCE_DEPLOY_LEDGER:-}" ]] && [[ -n "${COMPLIANCE_CONTRACT_ID}" ]]; then
  COMPLIANCE_DEPLOY_LEDGER="$("${ROOT}/scripts/dev/compliance-deploy-ledger.sh" "${COMPLIANCE_CONTRACT_ID}" 2>/dev/null || true)"
  [[ -n "${COMPLIANCE_DEPLOY_LEDGER}" ]] && export COMPLIANCE_DEPLOY_LEDGER
fi
export VALIDATE_START_LEDGER="${VALIDATE_START_LEDGER:-${COMPLIANCE_DEPLOY_LEDGER:-}}"

sync_frontend_env() {
  cat >"${ROOT}/frontend/.env.local" <<EOF
# Generated by scripts/dev/bru.sh
VITE_STELLAR_RPC_URL=${STELLAR_RPC_URL}
VITE_NETWORK_PASSPHRASE=${NETWORK_PASSPHRASE}
VITE_VERIFIER_CONTRACT_ID=${VERIFIER_CONTRACT_ID}
VITE_COMPLIANCE_CONTRACT_ID=${COMPLIANCE_CONTRACT_ID}
VITE_SAC_CONTRACT_ID=${SAC_CONTRACT_ID:-${ASSET_ID:-}}
VITE_ISSUER_PUBLIC_KEY=${ISSUER_PUBLIC_KEY}
VITE_ISSUER_URL=/issuer
VITE_ISSUER_ADMIN_TOKEN=${ISSUER_API_TOKEN:-demo-token}
VITE_WISP_FIXTURE_PROFILE=${WISP_FIXTURE_PROFILE}
VITE_VALIDATE_START_LEDGER=${VALIDATE_START_LEDGER:-}
VITE_WISP_WASM_URL=/circuits/compliance_corridor.wasm
VITE_WISP_ZKEY_URL=/circuits/compliance_corridor_final.zkey
VITE_WISP_DEMO_FIXTURE_URL=/fixtures/demo-transfer-testnet.json
EOF
}
sync_frontend_env

if [[ -z "${COMPLIANCE_CONTRACT_ID}" ]]; then
  echo "[bru] COMPLIANCE_CONTRACT_ID missing — run bootstrap-testnet-demo.sh" >&2
  exit 1
fi
if [[ -z "${ISSUER_PUBLIC_KEY}" ]]; then
  echo "[bru] ISSUER_PUBLIC_KEY missing — run bootstrap-testnet-demo.sh" >&2
  exit 1
fi

DB_ENABLED=0
if [[ -n "${SUPABASE_DB_URL:-}" ]]; then
  DB_ENABLED=1
  log_bru "running issuer db migrations…"
  if "${ROOT}/scripts/deploy/migrate-issuer-db.sh"; then
    log_bru "db migrations ok"
  elif [[ "${REQUIRE_DB}" == "1" ]]; then
    exit 1
  else
    log_bru "db unreachable in local mode, falling back to ISSUER_STATE_PATH"
    unset SUPABASE_DB_URL
    unset DATABASE_URL
    DB_ENABLED=0
  fi
fi

mkdir -p "${ROOT}/.wisp"

LAST_COMPLIANCE_FILE="${ROOT}/.wisp/last-compliance-id"
REPUBLISH_ROOTS=0
if [[ -n "${COMPLIANCE_CONTRACT_ID}" ]]; then
  if [[ -f "${LAST_COMPLIANCE_FILE}" ]] && [[ "$(tr -d '[:space:]' < "${LAST_COMPLIANCE_FILE}")" != "${COMPLIANCE_CONTRACT_ID}" ]]; then
    REPUBLISH_ROOTS=1
  fi
  echo "${COMPLIANCE_CONTRACT_ID}" > "${LAST_COMPLIANCE_FILE}"
fi

if [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
  kill "$(cat "$PIDFILE")" 2>/dev/null || true
  for _ in $(seq 1 20); do
    kill -0 "$(cat "$PIDFILE")" 2>/dev/null || break
    sleep 0.1
  done
fi
pkill -f 'target/debug/issuer-service' 2>/dev/null || true
for _ in $(seq 1 10); do
  ss -tln 2>/dev/null | grep -q ':3000 ' || break
  sleep 0.1
done

cleanup() {
  if [[ -f "$PIDFILE" ]]; then
    kill "$(cat "$PIDFILE")" 2>/dev/null || true
    for _ in $(seq 1 20); do
      kill -0 "$(cat "$PIDFILE")" 2>/dev/null || break
      sleep 0.1
    done
    rm -f "$PIDFILE"
  fi
}
trap cleanup EXIT INT TERM

STORE="memory"
[[ "${DB_ENABLED}" == "1" ]] && STORE="postgres"
if [[ "${STORE}" == "memory" ]]; then
  log_bru "KYC persists via ISSUER_STATE_PATH=${ISSUER_STATE_PATH} (set SUPABASE_DB_URL for Postgres)"
fi
log_bru "compliance=${COMPLIANCE_CONTRACT_ID} | issuer=${ISSUER_PUBLIC_KEY} | kyc=${KYC_MODE} | ${STORE}"
log_bru "issuer http://${ISSUER_LISTEN_ADDR} | frontend http://localhost:${FRONTEND_PORT}"

log_bru "building issuer-service…"
if ! cargo build -p issuer-service >>"$LOGFILE" 2>&1; then
  echo "[bru] issuer build failed — see ${LOGFILE}" >&2
  exit 1
fi

log_bru "starting issuer-service…"
"${ROOT}/target/debug/issuer-service" >>"$LOGFILE" 2>&1 &
echo $! >"$PIDFILE"

for i in $(seq 1 60); do
  if curl -sf "http://${ISSUER_LISTEN_ADDR}/health" >/dev/null 2>&1; then
    log_bru "issuer healthy (${i}s)"
    break
  fi
  if [[ "$i" -eq 1 || $((i % 5)) -eq 0 ]]; then
    log_bru "waiting for issuer… (${i}s)"
  fi
  sleep 1
done

if ! curl -sf "http://${ISSUER_LISTEN_ADDR}/health" >/dev/null 2>&1; then
  echo "[bru] issuer failed — see ${LOGFILE}" >&2
  exit 1
fi

if "${ROOT}/scripts/dev/seed-testnet-issuer.sh"; then
  log_bru "issuer seed ok"
else
  echo "[bru] issuer seed skipped or failed — see ${LOGFILE}" >&2
fi

if [[ "${REPUBLISH_ROOTS}" == "1" ]]; then
  log_bru "republishing roots…"
  if "${ROOT}/scripts/dev/publish-roots-testnet-via-issuer.sh"; then
    log_bru "roots ok"
  else
    echo "[bru] root republish failed — see ${LOGFILE}" >&2
  fi
fi

if [[ "${DB_ENABLED}" == "1" ]]; then
  if "${ROOT}/scripts/dev/patch-corridor-circle-asset.sh"; then
    log_bru "corridor asset ok"
  else
    echo "[bru] corridor asset patch skipped" >&2
  fi
fi

pnpm dev:frontend
