#!/usr/bin/env bash
# Start issuer-service + frontend dev server (testnet profile).
# Usage: ./scripts/dev/bru.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PIDFILE="${ROOT}/.amoeba/issuer-service.pid"
LOGFILE="${ROOT}/.amoeba/issuer-service.log"
FRONTEND_PORT="${FRONTEND_PORT:-5173}"
cd "$ROOT"

log_bru() {
  echo "[bru] $*"
}

# shellcheck disable=SC1091
[[ -f "${ROOT}/.env" ]] && source "${ROOT}/.env"
# shellcheck disable=SC1091
[[ -f "${ROOT}/.amoeba/testnet-demo.env" ]] && source "${ROOT}/.amoeba/testnet-demo.env"
# shellcheck disable=SC1091
[[ -f "${ROOT}/.amoeba/compliance.env" ]] && source "${ROOT}/.amoeba/compliance.env"

export ISSUER_LISTEN_ADDR="${ISSUER_LISTEN_ADDR:-127.0.0.1:3000}"
export ISSUER_STATE_PATH="${ISSUER_STATE_PATH:-${ROOT}/.amoeba/issuer-state-testnet.json}"
export ISSUER_API_TOKEN="${ISSUER_API_TOKEN:-demo-token}"
export AMOEBA_FIXTURES_DIR="${AMOEBA_FIXTURES_DIR:-${ROOT}/bindings/fixtures}"
export AMOEBA_FIXTURE_PROFILE="${AMOEBA_FIXTURE_PROFILE:-testnet}"
export COMPLIANCE_CONTRACT_ID="${COMPLIANCE_ID:-${COMPLIANCE_CONTRACT_ID:-}}"
export ISSUER_PUBLIC_KEY="${ISSUER_PUBLIC_KEY:-}"
export PUBLISH_SOURCE_ACCOUNT="${PUBLISH_SOURCE_ACCOUNT:-amoeba-issuer}"
export ADMIN_PUBLIC_KEY="${ADMIN_PUBLIC_KEY:-$(stellar keys public-key "amoeba-admin" 2>/dev/null || true)}"
export STELLAR_RPC_URL="${STELLAR_RPC_URL:-https://soroban-testnet.stellar.org}"
export NETWORK_PASSPHRASE="${NETWORK_PASSPHRASE:-Test SDF Network ; September 2015}"
export STELLAR_NETWORK_PASSPHRASE="${STELLAR_NETWORK_PASSPHRASE:-$NETWORK_PASSPHRASE}"
export WEB_AUTH_DOMAIN="${WEB_AUTH_DOMAIN:-localhost}"
export HORIZON_URL="${HORIZON_URL:-https://horizon-testnet.stellar.org}"
export KYC_MODE="${KYC_MODE:-sep10}"
export RUST_LOG="${RUST_LOG:-issuer_service=info,tower_http=info}"
export PROVIDER_WEBHOOK_SECRETS="${PROVIDER_WEBHOOK_SECRETS:-fixture=demo-fixture-secret}"

log_bru "compliance=${COMPLIANCE_CONTRACT_ID}"
log_bru "issuer=${ISSUER_PUBLIC_KEY} publish_source=${PUBLISH_SOURCE_ACCOUNT}"
log_bru "fixture=${AMOEBA_FIXTURE_PROFILE} kyc=${KYC_MODE} store=$([[ -n "${SUPABASE_DB_URL:-}" ]] && echo postgres || echo memory)"

if [[ -z "${COMPLIANCE_DEPLOY_LEDGER:-}" ]] && [[ -n "${COMPLIANCE_CONTRACT_ID}" ]]; then
  COMPLIANCE_DEPLOY_LEDGER="$("${ROOT}/scripts/dev/compliance-deploy-ledger.sh" "${COMPLIANCE_CONTRACT_ID}" 2>/dev/null || true)"
  if [[ -n "${COMPLIANCE_DEPLOY_LEDGER}" ]]; then
    export COMPLIANCE_DEPLOY_LEDGER
    log_bru "resolved COMPLIANCE_DEPLOY_LEDGER=${COMPLIANCE_DEPLOY_LEDGER}"
  fi
fi
export VALIDATE_START_LEDGER="${VALIDATE_START_LEDGER:-${COMPLIANCE_DEPLOY_LEDGER:-}}"

sync_frontend_env() {
  local f="${ROOT}/frontend/.env.local"
  cat >"$f" <<EOF
# Generated by scripts/dev/bru.sh
VITE_STELLAR_RPC_URL=${STELLAR_RPC_URL}
VITE_NETWORK_PASSPHRASE=${NETWORK_PASSPHRASE}
VITE_VERIFIER_CONTRACT_ID=${VERIFIER_CONTRACT_ID:-${VERIFIER_ID:-}}
VITE_COMPLIANCE_CONTRACT_ID=${COMPLIANCE_CONTRACT_ID}
VITE_SAC_CONTRACT_ID=${SAC_CONTRACT_ID:-}
VITE_ISSUER_PUBLIC_KEY=${ISSUER_PUBLIC_KEY}
VITE_ISSUER_URL=/issuer
VITE_AMOEBA_FIXTURE_PROFILE=${AMOEBA_FIXTURE_PROFILE}
VITE_VALIDATE_START_LEDGER=${VALIDATE_START_LEDGER:-}
EOF
  log_bru "wrote ${f}"
}
sync_frontend_env

if [[ -z "${COMPLIANCE_CONTRACT_ID}" ]]; then
  echo "COMPLIANCE_CONTRACT_ID missing — run bootstrap-testnet-demo.sh first" >&2
  exit 1
fi
if [[ -z "${ISSUER_PUBLIC_KEY}" ]]; then
  echo "ISSUER_PUBLIC_KEY missing — run bootstrap-testnet-demo.sh first" >&2
  exit 1
fi

if [[ -n "${SUPABASE_DB_URL:-}" ]]; then
  if ! command -v psql >/dev/null 2>&1; then
    echo "SUPABASE_DB_URL is set but psql is not installed — mock KYC needs schema migration" >&2
    exit 1
  fi
  echo "Applying issuer schema (idempotent) → Supabase"
  log_bru "supabase schema migrate"
  for migration in \
    "${ROOT}/backend/crates/issuer-service/migrations/001_supabase_issuer.sql" \
    "${ROOT}/backend/crates/issuer-service/migrations/002_mock_kyc_challenges.sql" \
    "${ROOT}/backend/crates/issuer-service/migrations/003_root_snapshots_compliance_contract.sql"; do
    if [[ ! -f "${migration}" ]]; then
      echo "missing migration: ${migration}" >&2
      exit 1
    fi
    PGOPTIONS='-c client_min_messages=warning' psql "${SUPABASE_DB_URL}" -v ON_ERROR_STOP=1 -q -f "${migration}"
  done
else
  log_bru "supabase unset — using in-memory store"
  echo "SUPABASE_DB_URL unset — issuer will use in-memory store (mock KYC still works locally)"
fi

mkdir -p "${ROOT}/.amoeba"

LAST_COMPLIANCE_FILE="${ROOT}/.amoeba/last-compliance-id"
REPUBLISH_ROOTS=0
if [[ ! -f "${ISSUER_STATE_PATH}" ]]; then
  REPUBLISH_ROOTS=1
  log_bru "fresh issuer state — will republish roots after startup"
  echo "Fresh issuer state — will republish roots after startup"
fi
if [[ -n "${COMPLIANCE_CONTRACT_ID}" ]]; then
  if [[ -f "${LAST_COMPLIANCE_FILE}" ]] && [[ "$(tr -d '[:space:]' < "${LAST_COMPLIANCE_FILE}")" != "${COMPLIANCE_CONTRACT_ID}" ]]; then
    REPUBLISH_ROOTS=1
    log_bru "compliance contract changed — will republish roots after startup"
    echo "Compliance contract changed — will republish issuer roots after startup"
  fi
  echo "${COMPLIANCE_CONTRACT_ID}" > "${LAST_COMPLIANCE_FILE}"
fi

if [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
  kill "$(cat "$PIDFILE")" || true
  sleep 1
fi

cleanup() {
  if [[ -f "$PIDFILE" ]]; then
    kill "$(cat "$PIDFILE")" 2>/dev/null || true
    rm -f "$PIDFILE"
  fi
}
trap cleanup EXIT INT TERM

echo "issuer-service (testnet) → http://${ISSUER_LISTEN_ADDR}"
echo "  state:   ${ISSUER_STATE_PATH}"
echo "  fixture: ${AMOEBA_FIXTURE_PROFILE}"
echo "  kyc:     ${KYC_MODE} (domain=${WEB_AUTH_DOMAIN})"
echo "  rustlog: ${RUST_LOG}"
echo "  log:     ${LOGFILE}"
echo ""
echo "frontend → http://localhost:${FRONTEND_PORT}  (/issuer → issuer-service)"
echo ""
echo "Operator checklist:"
echo "  1. ./scripts/dev/bootstrap-testnet-demo.sh  (Circle SAC + contracts + fixtures)"
echo "  2. ./scripts/dev/check-circle-usdc-testnet.sh  (fund sender if fail)"
echo "  3. ./scripts/dev/bru.sh  (issuer + frontend)"
echo "  4. Freighter testnet → SEP-10 sign → approve USDC → validate package → prove → settle"
echo "     Root drift? ./scripts/dev/publish-roots-testnet-via-issuer.sh"
echo "     Set COMPLIANCE_DEPLOY_LEDGER (or VALIDATE_START_LEDGER) if validate cannot find roots"
echo "     Third-party issuer? pnpm test:issuer-conformance -- --seed"
echo ""

cargo run -p issuer-service >>"$LOGFILE" 2>&1 &
echo $! >"$PIDFILE"

for _ in $(seq 1 30); do
  if curl -sf "http://${ISSUER_LISTEN_ADDR}/health" >/dev/null 2>&1; then
    break
  fi
  sleep 1
done

if ! curl -sf "http://${ISSUER_LISTEN_ADDR}/health" >/dev/null 2>&1; then
  echo "issuer-service failed to start — see ${LOGFILE}" >&2
  exit 1
fi
log_bru "issuer-service healthy"

if [[ "${REPUBLISH_ROOTS}" == "1" ]]; then
  log_bru "republishing roots for compliance ${COMPLIANCE_CONTRACT_ID}"
  echo "Republishing roots for compliance contract ${COMPLIANCE_CONTRACT_ID}"
  if "${ROOT}/scripts/dev/publish-roots-testnet-via-issuer.sh"; then
    log_bru "root republish ok"
  else
    log_bru "root republish failed — see ${LOGFILE} or run ./scripts/dev/publish-roots-testnet-via-issuer.sh"
    echo "WARN: root republish failed — run ./scripts/dev/publish-roots-testnet-via-issuer.sh" >&2
  fi
fi

if [[ -n "${SUPABASE_DB_URL:-}" ]]; then
  log_bru "patching corridor asset to Circle USDC SAC bytes"
  if "${ROOT}/scripts/dev/patch-corridor-circle-asset.sh"; then
    log_bru "corridor asset patch ok"
  else
    log_bru "corridor asset patch skipped"
    echo "WARN: corridor asset patch skipped — run ./scripts/dev/patch-corridor-circle-asset.sh after issuer is up" >&2
  fi
fi

pnpm dev:frontend
